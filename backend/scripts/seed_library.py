def build_docx(sample: dict) -> bytes:
    number, name, plaintiff, defendant = sample["case"]
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "바탕"
    style.font.size = Pt(12)
    style.element.rPr.rFonts.set(qn("w:eastAsia"), "바탕")

    def line(text: str, *, align=None, bold=False, size=None, after=6) -> None:
        paragraph = doc.add_paragraph()
        run = paragraph.add_run(text)
        run.bold = bold
        if size:
            run.font.size = Pt(size)
        paragraph.paragraph_format.space_after = Pt(after)
        if align is not None:
            paragraph.alignment = align

    heading = sample["heading"]
    line(" ".join(heading) if len(heading) <= 6 else heading, align=WD_ALIGN_PARAGRAPH.CENTER, bold=True, size=20, after=14)
    line(f"사        건    {number}  {name}")
    line(f"원        고    {plaintiff}")
    line(f"피        고    {defendant}", after=14)
    if sample["side"]:
        line(f"위 사건에 관하여 {sample['side']}는 다음과 같이 변론을 준비합니다.")
        line("다        음", align=WD_ALIGN_PARAGRAPH.CENTER, after=10)
    for section_heading, paragraphs in sample["sections"]:
        line(section_heading, bold=True, after=4)
        for text in paragraphs:
            line(text, after=8)
    if sample["evidence"]:
        line("입  증  방  법", align=WD_ALIGN_PARAGRAPH.CENTER, bold=True, after=4)
        for e in sample["evidence"]:
            line(f"1. {e}", after=2)
    line("")
    line("2025. 12. 1.", align=WD_ALIGN_PARAGRAPH.CENTER, after=10)
    line(f"{sample['side'] or '신청인'}  소송대리인  (서명 또는 날인)", align=WD_ALIGN_PARAGRAPH.RIGHT, after=14)
    line("○○지방법원  귀중", bold=True, size=14)
    line(FOOTER, size=9)
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def seed() -> None:
    settings = get_settings()
    embedder = OllamaEmbedder(settings.ollama_url, settings.embedding_model, settings.ollama_num_gpu) if settings.embeddings_enabled else None
    factory = get_session_factory()
    added = skipped = 0
    with factory() as session:
        session.info["actor"] = "seed"
        existing = {t for t in session.scalars(select(LibraryDoc.title))}
        for sample in SAMPLES:
            title = PREFIX + sample["title"]
            if title in existing:
                skipped += 1
                continue
            data = build_docx(sample)
            file = repo.save_file(session, f"{title}.docx", data, mime=DOCX_MIME)
            doc = library_store.add(session, title=title, kind=sample["kind"], file=file, mime=DOCX_MIME, case=None, embedder=embedder)
            session.commit()
            added += 1
            print(f"넣음: {title} (조각 {doc.chunk_count}, 임베딩 {'있음' if doc.embedded else '없음'})")
    print(f"완료: {added}건 넣고 {skipped}건은 이미 있어 건너뛰었습니다.")


def remove() -> None:
    factory = get_session_factory()
    with factory() as session:
        session.info["actor"] = "seed"
        docs = [d for d in session.scalars(select(LibraryDoc)) if d.title.startswith(PREFIX)]
        for doc in docs:
            library_store.remove(session, doc)
        session.commit()
    print(f"{len(docs)}건을 지웠습니다.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--remove", action="store_true", help="[가상]으로 시작하는 자료를 모두 지운다")
    args = parser.parse_args()
    remove() if args.remove else seed()
